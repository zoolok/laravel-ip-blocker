<?php

namespace Zoolok\IpBlocker\Tests\Services;

use PHPUnit\Framework\TestCase;
use Zoolok\IpBlocker\Services\DenyGenerator;

class DenyGeneratorTest extends TestCase
{
    private string $tempDir;

    protected function setUp(): void
    {
        $this->tempDir = sys_get_temp_dir().'/ip-blocker-test-'.uniqid();
        mkdir($this->tempDir, 0777, true);
    }

    protected function tearDown(): void
    {
        $this->removeDirectory($this->tempDir);
    }

    public function test_generates_nginx_config_with_single_ip(): void
    {
        $denyPath = $this->tempDir.'/blocked-ips.conf';

        $generator = new DenyGenerator(
            serverType: 'nginx',
            denyPath: $denyPath,
            reloadCommand: 'echo reloaded',
        );

        $result = $generator->generate(['192.168.1.1']);

        $this->assertTrue($result);
        $this->assertFileExists($denyPath);

        $content = file_get_contents($denyPath);

        $this->assertStringContainsString('deny 192.168.1.1;', $content);
        $this->assertStringContainsString('# Auto-generated by laravel-ip-blocker', $content);
    }

    public function test_generates_nginx_config_with_multiple_ips(): void
    {
        $denyPath = $this->tempDir.'/blocked-ips.conf';

        $generator = new DenyGenerator(
            serverType: 'nginx',
            denyPath: $denyPath,
            reloadCommand: 'echo reloaded',
        );

        $result = $generator->generate(['10.0.0.1', '192.168.1.1', '::1']);

        $this->assertTrue($result);

        $content = file_get_contents($denyPath);

        $this->assertStringContainsString('deny 10.0.0.1;', $content);
        $this->assertStringContainsString('deny 192.168.1.1;', $content);
        $this->assertStringContainsString('deny ::1;', $content);
    }

    public function test_generates_apache_config(): void
    {
        $htaccessPath = $this->tempDir.'/.htaccess';

        $generator = new DenyGenerator(
            serverType: 'apache',
            denyPath: '/unused',
            reloadCommand: 'echo reloaded',
            allowOverridePath: $htaccessPath,
        );

        $result = $generator->generate(['10.0.0.1', '192.168.1.1']);

        $this->assertTrue($result);
        $this->assertFileExists($htaccessPath);

        $content = file_get_contents($htaccessPath);

        $this->assertStringContainsString('Require not ip 10.0.0.1', $content);
        $this->assertStringContainsString('Require not ip 192.168.1.1', $content);
        $this->assertStringContainsString('<Limit GET POST PUT PATCH DELETE>', $content);
        $this->assertStringContainsString('</Limit>', $content);
    }

    public function test_generates_header_only_for_empty_ips(): void
    {
        $denyPath = $this->tempDir.'/blocked-ips.conf';

        $generator = new DenyGenerator(
            serverType: 'nginx',
            denyPath: $denyPath,
            reloadCommand: 'echo reloaded',
        );

        $result = $generator->generate([]);

        $this->assertTrue($result);

        $content = file_get_contents($denyPath);

        $this->assertStringContainsString('# Auto-generated by laravel-ip-blocker', $content);
        $this->assertStringNotContainsString('deny ;', $content);
    }

    public function test_creates_directory_if_not_exists(): void
    {
        $nestedPath = $this->tempDir.'/subdir/config/blocked-ips.conf';

        $generator = new DenyGenerator(
            serverType: 'nginx',
            denyPath: $nestedPath,
            reloadCommand: 'echo reloaded',
        );

        $result = $generator->generate(['10.0.0.1']);

        $this->assertTrue($result);
        $this->assertFileExists($nestedPath);
    }

    public function test_returns_false_on_write_failure(): void
    {
        $generator = new DenyGenerator(
            serverType: 'nginx',
            denyPath: '/nonexistent-dir-12345/blocked-ips.conf',
            reloadCommand: 'echo reloaded',
        );

        $result = $generator->generate(['10.0.0.1']);

        $this->assertFalse($result);
    }

    private function removeDirectory(string $dir): void
    {
        if (! is_dir($dir)) {
            return;
        }

        $files = array_diff(scandir($dir) ?: [], ['.', '..']);

        foreach ($files as $file) {
            $filePath = $dir.'/'.$file;

            if (is_file($filePath)) {
                unlink($filePath);
            } else {
                $this->removeDirectory($filePath);
            }
        }

        rmdir($dir);
    }
}
